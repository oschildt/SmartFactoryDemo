-- Oracle 12c or later. Run in a newly created, empty demo schema.
-- Identity START WITH values follow the explicit IDs in init_data.sql.

create table dbworker_locks (
    resource_key char(64 byte) not null,
    resource_name clob null,
    constraint dbworker_locks_pk primary key (resource_key)
);

create table department (
  id integer generated by default as identity (start with 5) not null,
  name varchar2(250 char) not null,
  constraint department_pk primary key (id),
  constraint department_name_unq unique (name)
);

create table large_data (
  id integer not null,
  blob_data blob,
  text_data clob
);

create table page_content (
  language_key varchar2(3 char) not null,
  page_id integer not null,
  title varchar2(250 char) default null,
  content varchar2(250 char) default null,
  constraint page_content_unq unique (language_key, page_id)
);

create table pages (
  id integer generated by default as identity (start with 7) not null,
  page_name varchar2(250 char) not null,
  page_type varchar2(20 char) not null,
  page_order integer default null,
  page_date timestamp(0) default null,
  constraint pages_pk primary key (id),
  constraint page_name_unq unique (page_name)
);

create table room_prices (
  room varchar2(250 char) not null,
  dt date not null,
  price number(12,2) default null
);

create table settings (
  id integer default 1 not null,
  data clob,
  constraint settings_pk primary key (id)
);

create table users (
  id integer generated by default as identity (start with 11) not null,
  email varchar2(255 char) default null,
  last_name varchar2(500 char) not null,
  first_name varchar2(500 char) default null,
  birth_date date default null,
  salary number(12,2) default null,
  department_id integer not null,
  language varchar2(20 char) default null,
  time_zone varchar2(20 char) default null,
  last_login timestamp(0) default null,
  constraint users_pk primary key (id)
);

create table user_forum_settings (
  user_id integer not null,
  signature varchar2(250 char) default null,
  status varchar2(250 char) default null,
  hide_pictures integer default 0 not null,
  hide_signatures integer default 0 not null,
  constraint user_forum_settings_pk primary key (user_id)
);

create table user_colors (
  user_id integer not null,
  color varchar2(255 char) default null,
  constraint user_colors_unq unique (user_id, color)
);

-- The table definition is shared; its contents are private to each session.
-- Preserve rows across commits, matching the other demo procedures.
create global temporary table temp (
  email varchar2(255 char) default null,
  last_name varchar2(500 char) not null,
  first_name varchar2(500 char) default null
) on commit preserve rows;

create or replace procedure collect_users(p_min_salary in number)
as
begin
  delete from temp;

  insert into temp (email, last_name, first_name)
  select email, last_name, first_name from users where salary >= p_min_salary;
end;
/

